function updatePrayerList() {
  const selectedPrayer = prayerSelect.value;
  const selectedCategory = categorySelect.value;
  const selectedSubcategory = subcategorySelect.value;
  const searchText = searchInput.value
    .trim()
    .toLowerCase();

  const filteredPrayers = prayers.filter(function (
    prayer,
    index
  ) {
    const matchesPrayer =
      selectedPrayer === "all" ||
      selectedPrayer === String(index);

    const matchesCategory =
      selectedCategory === "all" ||
      prayer.category === selectedCategory;

    const matchesSubcategory =
      selectedSubcategory === "all" ||
      prayer.subcategory === selectedSubcategory;

    const searchableText = `
      ${prayer.title}
      ${prayer.category}
      ${prayer.subcategory}
      ${prayer.text}
    `.toLowerCase();

    const matchesSearch =
      searchableText.includes(searchText);

    return (
      matchesPrayer &&
      matchesCategory &&
      matchesSubcategory &&
      matchesSearch
    );
  });

  displayPrayers(filteredPrayers);
}

prayerSelect.addEventListener(
  "change",
  updatePrayerList
);

categorySelect.addEventListener(
  "change",
  updatePrayerList
);

subcategorySelect.addEventListener(
  "change",
  updatePrayerList
);

searchInput.addEventListener(
  "input",
  updatePrayerList
);

loadPrayerOptions();
